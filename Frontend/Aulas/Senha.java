public class Senha{
    public static void main(String[] args) {

        int senha = 1234;
        int tentativa = 0;
        
        while (tentativa != senha){
            tentativa= 1234;
            System.out.println("Acesso negado");

            if (tentativa == senha);
                System.out.println("Tentando acessar...");
        }
        System.out.println("Acesso liberado");
    }
}